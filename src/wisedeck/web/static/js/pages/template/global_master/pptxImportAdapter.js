/**
 * PPTX 导入适配器 - 将后端 JSON 数据转换为前端渲染所需的格式
 * 
 * 核心功能：
 * 1. 坐标比例转百分比字符串
 * 2. 适配模板配置
 * 3. 生成预览 HTML
 */

const PptxImportAdapter = (function() {
    'use strict';

    const DEFAULT_COLORS = {
        primary: '#4472C4',
        background: '#FFFFFF',
        accent1: '#4472C4',
        accent2: '#ED7D31',
        accent3: '#A5A5A5',
        accent4: '#FFC000',
        accent5: '#5B9BD5',
        accent6: '#70AD47',
    };

    const DEFAULT_FONTS = {
        title: 'Arial',
        body: 'Calibri',
    };

    const PLACEHOLDER_LABELS = {
        PAGE_TITLE: '标题',
        SUBTITLE: '副标题',
        CONTENT_AREA: '内容区域',
        CONTENT_AREA_LEFT: '左栏内容',
        CONTENT_AREA_RIGHT: '右栏内容',
        CONTENT_AREA_CENTER: '中栏内容',
        CHART_AREA: '图表区域',
        TABLE_AREA: '表格区域',
    };

    function ratioToPercent(ratio) {
        const num = parseFloat(ratio);
        if (isNaN(num)) return '0%';
        const percent = Math.round(num * 100);
        return `${Math.max(0, Math.min(100, percent))}%`;
    }

    function bboxRatioToStyles(bboxRatio) {
        if (!Array.isArray(bboxRatio) || bboxRatio.length !== 4) {
            return {
                left: '0%',
                top: '0%',
                width: '0%',
                height: '0%',
            };
        }
        return {
            left: ratioToPercent(bboxRatio[0]),
            top: ratioToPercent(bboxRatio[1]),
            width: ratioToPercent(bboxRatio[2]),
            height: ratioToPercent(bboxRatio[3]),
        };
    }

    function adaptPlaceholder(placeholder) {
        const type = placeholder.type || 'CONTENT_AREA';
        const bboxRatio = placeholder.bbox_ratio || placeholder.bboxRatio || [0, 0, 0, 0];
        const styles = bboxRatioToStyles(bboxRatio);
        
        return {
            type: type,
            label: PLACEHOLDER_LABELS[type] || type,
            x: styles.left,
            y: styles.top,
            width: styles.width,
            height: styles.height,
            bboxRatio: bboxRatio,
            bboxPx: placeholder.bbox_px || placeholder.bboxPx || null,
        };
    }

    function adaptLayout(layout) {
        const adapted = {
            layoutIndex: layout.layout_index ?? layout.layoutIndex ?? 0,
            layoutName: layout.layout_name || layout.layoutName || '未命名布局',
            placeholders: [],
            autoGenerated: null,
        };

        const placeholders = layout.placeholders || [];
        adapted.placeholders = placeholders.map(adaptPlaceholder);

        if (layout.auto_generated || layout.autoGenerated) {
            const autoGen = layout.auto_generated || layout.autoGenerated;
            adapted.autoGenerated = {
                twoColumn: null,
                threeColumn: null,
            };

            if (autoGen.two_column || autoGen.twoColumn) {
                const tc = autoGen.two_column || autoGen.twoColumn;
                adapted.autoGenerated.twoColumn = {
                    left: adaptPlaceholder(tc.left),
                    right: adaptPlaceholder(tc.right),
                };
            }

            if (autoGen.three_column || autoGen.threeColumn) {
                const thc = autoGen.three_column || autoGen.threeColumn;
                adapted.autoGenerated.threeColumn = {
                    left: adaptPlaceholder(thc.left),
                    center: adaptPlaceholder(thc.center),
                    right: adaptPlaceholder(thc.right),
                };
            }
        }

        return adapted;
    }

    function adaptPptxTemplateConfig(backendJson) {
        if (!backendJson || typeof backendJson !== 'object') {
            return null;
        }

        const slideDimensions = backendJson.slide_dimensions || backendJson.slideDimensions || {};
        const themeColors = backendJson.theme_colors || backendJson.themeColors || DEFAULT_COLORS;
        const fonts = backendJson.fonts || DEFAULT_FONTS;
        const layouts = backendJson.layouts || [];

        const adapted = {
            schemaVersion: backendJson.schema_version || backendJson.schemaVersion || 1,
            source: backendJson.source || 'pptx_style_extractor',
            slideDimensions: {
                widthEmu: slideDimensions.width_emu || slideDimensions.widthEmu || 9144000,
                heightEmu: slideDimensions.height_emu || slideDimensions.heightEmu || 6858000,
                widthPt: slideDimensions.width_pt || slideDimensions.widthPt || 720,
                heightPt: slideDimensions.height_pt || slideDimensions.heightPt || 540,
            },
            themeColors: themeColors,
            fonts: fonts,
            layouts: layouts.map(adaptLayout),
            templateContract: backendJson.template_contract || backendJson.templateContract || {},
        };

        return adapted;
    }

    function generatePreviewHtml(templateConfig, options = {}) {
        const opts = {
            width: options.width || 640,
            height: options.height || 480,
            showPlaceholders: options.showPlaceholders !== false,
            showLabels: options.showLabels !== false,
            layoutIndex: options.layoutIndex ?? 0,
            useTwoColumn: options.useTwoColumn || false,
            useThreeColumn: options.useThreeColumn || false,
        };

        const adapted = adaptPptxTemplateConfig(templateConfig);
        if (!adapted) {
            return '<div style="padding:20px;color:#999;">无法生成预览</div>';
        }

        const bgColor = adapted.themeColors.background || '#FFFFFF';
        const titleColor = adapted.themeColors.primary || '#4472C4';
        const titleFont = adapted.fonts.title || 'Arial';
        const bodyFont = adapted.fonts.body || 'Calibri';

        const layout = adapted.layouts[opts.layoutIndex] || adapted.layouts[0];
        if (!layout) {
            return '<div style="padding:20px;color:#999;">无可用布局</div>';
        }

        let placeholders = [...layout.placeholders];

        if (opts.useTwoColumn && layout.autoGenerated?.twoColumn) {
            placeholders = placeholders.filter(p => p.type !== 'CONTENT_AREA');
            placeholders.push(layout.autoGenerated.twoColumn.left);
            placeholders.push(layout.autoGenerated.twoColumn.right);
        } else if (opts.useThreeColumn && layout.autoGenerated?.threeColumn) {
            placeholders = placeholders.filter(p => p.type !== 'CONTENT_AREA');
            placeholders.push(layout.autoGenerated.threeColumn.left);
            placeholders.push(layout.autoGenerated.threeColumn.center);
            placeholders.push(layout.autoGenerated.threeColumn.right);
        }

        let placeholderHtml = '';
        placeholders.forEach((ph, idx) => {
            const isTitle = ph.type === 'PAGE_TITLE';
            const isSubtitle = ph.type === 'SUBTITLE';
            const bgColor = isTitle ? 'transparent' : 
                           isSubtitle ? 'transparent' : 
                           'rgba(68, 114, 196, 0.1)';
            const borderColor = isTitle ? 'transparent' : 
                               isSubtitle ? 'transparent' : 
                               'rgba(68, 114, 196, 0.3)';
            const textColor = isTitle ? titleColor : 
                             isSubtitle ? '#666666' : 
                             '#333333';
            const fontFamily = isTitle || isSubtitle ? titleFont : bodyFont;
            const fontSize = isTitle ? '18px' : 
                            isSubtitle ? '14px' : 
                            '12px';
            const label = opts.showLabels ? 
                `<div style="position:absolute;top:2px;left:4px;font-size:10px;color:#999;background:rgba(255,255,255,0.8);padding:1px 4px;border-radius:2px;">${ph.label}</div>` : 
                '';

            placeholderHtml += `
                <div style="
                    position:absolute;
                    left:${ph.x};
                    top:${ph.y};
                    width:${ph.width};
                    height:${ph.height};
                    background:${bgColor};
                    border:1px dashed ${borderColor};
                    border-radius:4px;
                    display:flex;
                    align-items:center;
                    justify-content:center;
                    font-family:${fontFamily}, sans-serif;
                    font-size:${fontSize};
                    color:${textColor};
                    overflow:hidden;
                    box-sizing:border-box;
                ">
                    ${label}
                    <span style="opacity:0.5;">${isTitle ? '标题' : isSubtitle ? '副标题' : '内容'}</span>
                </div>
            `;
        });

        const html = `<!DOCTYPE html>
<html>
<head>
    <meta charset="UTF-8">
    <title>模板预览</title>
    <style>
        * { box-sizing: border-box; margin: 0; padding: 0; }
        body { 
            margin: 0; 
            padding: 0; 
            width: ${opts.width}px; 
            height: ${opts.height}px; 
            overflow: hidden;
            background: ${bgColor};
            font-family: ${bodyFont}, sans-serif;
        }
        .slide-container {
            position: relative;
            width: 100%;
            height: 100%;
        }
    </style>
</head>
<body>
    <div class="slide-container">
        ${placeholderHtml}
    </div>
</body>
</html>`;

        return html;
    }

    function generateAllLayoutPreviews(templateConfig, options = {}) {
        const adapted = adaptPptxTemplateConfig(templateConfig);
        if (!adapted || !adapted.layouts.length) {
            return [];
        }

        const previews = [];
        adapted.layouts.forEach((layout, idx) => {
            previews.push({
                layoutIndex: idx,
                layoutName: layout.layoutName,
                previewHtml: generatePreviewHtml(templateConfig, { ...options, layoutIndex: idx }),
                placeholderCount: layout.placeholders.length,
                hasTwoColumn: !!layout.autoGenerated?.twoColumn,
                hasThreeColumn: !!layout.autoGenerated?.threeColumn,
            });
        });

        return previews;
    }

    function toGlobalMasterTemplateData(templateConfig, metadata = {}) {
        const adapted = adaptPptxTemplateConfig(templateConfig);
        if (!adapted) {
            return null;
        }

        const primaryLayout = adapted.layouts[0] || { placeholders: [] };
        const previewHtml = generatePreviewHtml(templateConfig);

        return {
            template_name: metadata.templateName || '导入的模板',
            description: metadata.description || `从 PPTX 导入 - ${adapted.layouts.length} 个布局`,
            html_template: previewHtml,
            svg_template: null,
            preview_image: null,
            import_summary: {
                source: adapted.source,
                layout_count: adapted.layouts.length,
                placeholder_markers: adapted.templateContract.placeholder_markers || [],
                slide_dimensions: adapted.slideDimensions,
            },
            style_config: {
                colors: adapted.themeColors,
                fonts: adapted.fonts,
                layouts: adapted.layouts.map(l => ({
                    name: l.layoutName,
                    placeholders: l.placeholders.map(p => ({
                        type: p.type,
                        bbox: p.bboxRatio,
                    })),
                })),
            },
            tags: metadata.tags || ['导入模板', 'PPTX'],
            is_default: false,
            is_active: true,
        };
    }

    return {
        ratioToPercent,
        bboxRatioToStyles,
        adaptPlaceholder,
        adaptLayout,
        adaptPptxTemplateConfig,
        generatePreviewHtml,
        generateAllLayoutPreviews,
        toGlobalMasterTemplateData,
        DEFAULT_COLORS,
        DEFAULT_FONTS,
        PLACEHOLDER_LABELS,
    };
})();

if (typeof window !== 'undefined') {
    window.PptxImportAdapter = PptxImportAdapter;
}

if (typeof module !== 'undefined' && module.exports) {
    module.exports = PptxImportAdapter;
}
